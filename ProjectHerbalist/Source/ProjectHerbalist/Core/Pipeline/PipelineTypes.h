// ============================================================================
// Структуры для внутреннего использования в пайплайне (L2-представление)
// ============================================================================

/**
 * Результат агрегации ингредиентов в L2-пространстве.
 * Содержит нормализованное направление, отдельную магнитуду и мета-параметры.
 */
struct FAggregatedL2
{
    FL2Direction Dir;       // Направление (нормализовано на сфере)
    float Magnitude = 0.0f; // Сила эффекта
    FMeta Meta;             // Мета-параметры (агрегированы отдельно)

    FAggregatedL2()
        : Magnitude(0.0f)
    {}
};

/**
 * Дельта-изменение в L2-пространстве.
 * Может использоваться для передачи разницы между агрегированным состоянием
 * и текущим состоянием биома перед применением операторов Morok/Zaryana.
 */
struct FDeltaL2
{
    FL2Direction Dir;
    float Magnitude = 0.0f;
    FMeta Meta;

    FDeltaL2()
        : Magnitude(0.0f)
    {}
};