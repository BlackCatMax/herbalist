// Заготовки строк для карточек бестиария, у которых строки нет вовсе
// (2026-09-03, по итогам -run=CompendiumAudit). Дописывает в существующие
// таблицы, ничего не перезаписывая: строка с таким EntityID уже есть --
// пропускаем.
//
// ЧТО ЗАГОТОВКА НЕ ДЕЛАЕТ. Карточка даёт только идентичность и намерение
// (биом, ранг, оси d_manifest, morok_affinity). Порогов, ставок эффекта,
// гистерезиса и тай-брейков в компендиуме нет -- их придумывает
// геймдизайн, а не парсер. Поэтому ставки эффекта здесь НУЛЕВЫЕ: существо
// проявится и будет видно, но мир менять не станет, пока числа не
// проставят руками. Это тот же честный приём, что уже применён к Злыдням
// и Ржавым духам ("манифестируются без эффекта, заглушка до редизайна") --
// лучше видимая заглушка, чем выдуманный баланс, который потом примут за
// авторский.
//
// Порог Низшего ранга берётся из morok_affinity карточки: дух с высокой
// склонностью к Мороку проявляется там, где Distortion выше этого числа.
// Мэппинг простой и заведомо временный -- он ЕСТЬ только потому, что
// карточка без единого гейта отбрасывается загрузчиком реестра
// (GetAmbientEntityDefinitions) и молча не работала бы вовсе.
//
// Запуск: UnrealEditor-Cmd.exe <uproject> -run=BestiaryStubsAppend
