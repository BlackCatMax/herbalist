// BestiaryRankMoveCommandlet.h
//
// Перенос трёх существ из Основного ранга (DT_Landmarks) в Низший
// (DT_AmbientEntities) — Курганники, Жердяи, Курганные огни (2026-09-03,
// прямое решение пользователя: «истина в документации и коде, а не в
// ассетах в движке»).
//
// ЧТО ИМЕННО РАСХОДИЛОСЬ. Сверка -run=CompendiumAudit нашла у этих трёх
// расхождение ранга. Документация говорит «Низший» ЧЕТЫРЬМЯ независимыми
// местами:
//   - карточки бестиария: level: Низший (les_low_01, broad_low_03,
//     ste_low_01 -- сам идентификатор несёт "low");
//   - карточки биомов (Лесостепь/Широколиственный лес/Степь): все три
//     перечислены в строке "**Низшие:**";
//   - таблица §16.2 GDD (16_Entity_Manifestation.md): все три -- СТРОКИ
//     этой таблицы, то есть Низшие;
//   - список §16.3 там же ("Полевик, Аука, Дух Медведя, Хозяин Севера,
//     Гуменник, Овинник, Кикимора болотная, Переплут, Полудница, Бродницы,
//     Боровик, Луговой, Русалки") ни одного из трёх НЕ называет.
//
// Против этого стояла ровно одна фраза прозы §16.2 («Курганники/Жердяи --
// требовали "подношения", это уже §16.3, туда и перешли») и строки в
// LandmarksCreateCommandlet, где ставки Bless/Curse были выдуманы
// генератором ассета, а не взяты из документа. Курганные огни та фраза не
// называет вовсе -- они попали в Основной уже просто за компанию.
//
// Замечание к решению, которое стоит держать в виду: у Курганников и
// Жердяев колонка эффекта §16.2 действительно говорит про «подношения»/
// «уважение» -- механику Restoration, то есть Основного ранга. Перенос её
// НЕ уничтожает: запись в таблице §16.2 остаётся на месте как
// задокументированное, но не реализованное уточнение. Если геймдизайн
// решит иначе -- обратный перенос делается тем же способом.
//
// Ставки эффекта переносимых -- НУЛЕВЫЕ, тот же принцип, что у
// BestiaryStubsAppend: прежние Bless/Curse в DT_Landmarks были выдуманы
// генератором, переносить выдуманное число в другую схему значило бы
// закрепить его как авторское. Гейт же обязателен (иначе загрузчик
// реестра отбрасывает определение) и берётся из morok_affinity карточки;
// у Курганных огней вдобавок настоящий гейт из документа -- «сумерки»
// (bRequiresDusk, механика уже есть, её использует Шишиги).
//
// Запуск: UnrealEditor-Cmd.exe <uproject> -run=BestiaryRankMove
