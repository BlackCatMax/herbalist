// WorldStateMapSetupCommandlet.h
//
// Заводит ассеты, нужные карте состояния мира (2026-09-08, продолжение
// «плана A» от 2026-09-07). Сама выгрузка уже написана и покрыта тестами,
// но включается она только когда назначен render target — этот коммандлет
// его создаёт и назначает, чтобы не делать руками то, что машина делает
// одинаково.
//
// Что делает, всё идемпотентно:
//   1. Создаёт /Game/Materials/RT_WorldStateMap, если его нет.
//   2. Добавляет в MPC_WorldStateFields параметры WorldStateMapOrigin и
//      WorldStateMapSize, если их там ещё нет.
//   3. Назначает render target менеджеру сетки в L_Playtest и сохраняет
//      карту, если он ещё не назначен.
//
// ПОЧЕМУ ИМЕННО ТАКИЕ НАСТРОЙКИ У RENDER TARGET — три из них влияют на
// правильность, а не на вкус, и каждая молча ломает картинку, если её
// не выставить:
//
//   bForceLinearGamma = true. Это ДАННЫЕ, а не цвет. У RTF_RGBA8 по
//   умолчанию sRGB-кодирование, и тогда записанные 0.25 вернулись бы в
//   шейдер другим числом после гамма-декодирования. Значение перестало бы
//   означать то, что означает в симуляции, причём выглядело бы правдоподобно.
//
//   Filter = TF_Bilinear. Тексель тут — целая клетка мира (1 м на dev-карте,
//   10 м в продакшене). С TF_Nearest граница клеток была бы видна как
//   геометрический квадрат — ровно то, чего Calysto избегает шумовым
//   размытием у границ биомов. Билинейная фильтрация даёт плавный переход
//   между соседними клетками бесплатно. Математика при этом сходится сама:
//   UV центра клетки = (X + 0.5) / GridSize — это ровно центр текселя, то есть
//   в центре клетки читается её собственное значение без примеси соседей.
//
//   AddressX/Y = TA_Clamp. За краем сетки данных нет; повтор (Wrap)
//   означал бы, что мир за границей раскрашен состоянием противоположного
//   края сетки.
//
// Размер берётся из GridSizeX/GridSizeY менеджера на карте, а не задаётся
// параметром: разрешение карты — один тексель на клетку, и это свойство
// механизма, а не настройка (довод — в шапке GridWorldManagerWorldStateMap.cpp).
// Если менеджер на карте не найден, ассет всё равно создаётся: рантайм
// подгонит размер сам через ResizeTarget.
//
// Запуск: UnrealEditor-Cmd.exe <uproject> -run=WorldStateMapSetup
