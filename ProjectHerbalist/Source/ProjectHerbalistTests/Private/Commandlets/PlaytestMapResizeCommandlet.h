// PlaytestMapResizeCommandlet.h
//
// Меняет размер игровой сетки на уже существующей /Game/Maps/L_Playtest и
// заново раскладывает восемь биом-полос под новый размер (2026-09-07,
// решение пользователя: "множитель + увеличить тестовую сетку").
//
// Зачем отдельный коммандлет, а не правка PlaytestMapCreate. Тот
// идемпотентен и на существующей карте не делает ничего — а пересоздавать
// L_Playtest НЕЛЬЗЯ: в ней уже лежит собранный вручную ландшафт (370 КБ
// против 13 КБ у пустой L_TestDev). Пересоздание уничтожило бы работу,
// сделанную в редакторе. Этот коммандлет правит карту НА МЕСТЕ: трогает
// только `GridSizeX/GridSizeY` менеджера и сплайны биом-регионов, всё
// остальное — ландшафт, стол, PlayerStart — остаётся как есть.
//
// Зачем менять размер. Сетка 20x20 при `CellSize=100` (сантиметры!) — это
// мир ДВАДЦАТЬ МЕТРОВ в поперечнике, а минимальные дистанции между особями
// одного вида заданы в карточках как 15 и 30 метров. На такой карте
// помещается ровно одна особь вида на весь мир, а четыре карточки на 30 м
// не помещаются и так. Ручку под это уже завели
// (`UHerbalistSettings::EntitySpacingMultiplier`), но она лечит пропорцию,
// а не тесноту мира как таковую.
//
// ВАЖНО про ландшафт: он НЕ растягивается этим коммандлетом — это работа в
// редакторе. Клетки за его краем получат высоту 0 (`FindAndCacheLandscape`
// просто не найдёт под ними геометрии), мир от этого не сломается, но
// визуально будет обрыв. После запуска ландшафт нужно довести до нового
// размера руками.
//
// Запуск: UnrealEditor-Cmd.exe <uproject> -run=PlaytestMapResize [-size=128]
// По умолчанию 128 клеток в стороне (мир 128 м, четыре чанка по 32).
