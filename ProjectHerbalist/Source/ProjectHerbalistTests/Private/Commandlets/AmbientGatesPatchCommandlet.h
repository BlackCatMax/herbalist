// Точечно правит осевые гейты уже существующего /Game/Herbalist/Data/
// DT_AmbientEntities (2026-09-07, решение пользователя). Двум карточкам --
// Плескуны и Шептуны -- порог был задан как 0.0 на оси [0,1], то есть
// формально гейт есть, а условия нет: они срабатывали всегда.
//
// Последствие оказалось не косметическим. Низший ранг весь на приоритете 0,
// а CanManifest (GridWorldManagerEntities.cpp) не даёт вытеснить существо
// РАВНОГО ранга -- значит занявший клетку первым держит её, пока сам не
// перестанет проходить свой гейт. Карточка с вечно истинным гейтом не
// отпускает клетку никогда: Шептуны закрывали всю сухую тундру (Метельники,
// Ледяные духи, Снежные огни), Плескуны -- всю воду поймы (Русалки,
// Кувшинкины духи, Омутные огни). Найдено 2026-09-07, когда автотесты
// перестали молча гоняться на нулевых дефолтах биомов.
//
// Новые оси и пороги -- из карточек компендиума, не выдуманы:
//   Шептуны  (Тундра/Шептуны.md,  d_manifest [0.1, 0.5, 0.7, 0.4]) -> Spirit >= 0.40
//   Плескуны (Речная пойма/Плескуны.md, [0.2, 0.2, 0.5, 0.8])      -> Nature >= 0.40
// Природные значения соответствующих осей после NormalizeSum: тундра
// Spirit 0.30, пойма Nature 0.275 -- тот же запас над природой биома, что у
// уже принятых Трясинных духов (0.40 против 0.30) и Чащобных духов (0.45
// против 0.25).
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ КОММАНДЛЕТ, а не перегенерация ассета: сам
// AmbientEntitiesCreateCommandlet идемпотентен и на существующем ассете не
// делает ничего, а удалить ассет и создать заново нельзя -- в нём живут ещё
// две карточки (Лесавки, Степные духи), которых в его исходнике нет вовсе,
// их дописывает BestiaryStubsAppendCommandlet. Регенерация «с нуля» тихо
// удалила бы обеих. Тот же приём правки на месте, что у остальных
// *AppendCommandlet проекта. Исходник генератора обновлён параллельно,
// чтобы создание с нуля давало те же числа.
//
// Идемпотентен: строка, уже стоящая на нужной оси с нужным порогом,
// пропускается.
//
